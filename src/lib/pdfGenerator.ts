import jsPDF from 'jspdf';
import { Quotation, Invoice } from './types';

export function generateQuotationPDF(qt: Quotation): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  // Header Branding
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.setTextColor(30, 64, 175); // Royal Blue
  doc.text('NUNC BUSINESS SOLUTIONS', 20, 25);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139); // Slate 500
  doc.text('Technology & Business Solutions Provider', 20, 31);
  doc.text('nuncbusinesssolutions@gmail.com | 09161669188', 20, 36);
  doc.text('nuncbusinesssolutions.ph', 20, 41);

  // Document Title & Meta Box
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42); // Slate 900
  doc.text('PROJECT QUOTATION', 130, 25);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text(`Quotation No: ${qt.quotationNumber}`, 130, 32);
  doc.text(`Date Issued: ${new Date(qt.createdAt).toLocaleDateString()}`, 130, 37);
  doc.text(`Valid Until: ${qt.validUntil}`, 130, 42);
  doc.text(`Currency: ${qt.currency}`, 130, 47);

  // Dividing Line
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(20, 52, 190, 52);

  // Client Details Box
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(30, 64, 175);
  doc.text('PREPARED FOR:', 20, 60);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text(qt.clientBusiness || qt.clientName, 20, 66);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text(`Attention: ${qt.clientName}`, 20, 71);
  doc.text(`Email: ${qt.clientEmail}`, 20, 76);
  doc.text(`Project: ${qt.projectTitle}`, 20, 81);

  // Line Items Table Header
  let y = 92;
  doc.setFillColor(248, 250, 252);
  doc.rect(20, y, 170, 8, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(30, 41, 59);
  doc.text('Description', 24, y + 5.5);
  doc.text('Qty', 115, y + 5.5);
  doc.text('Unit Price', 135, y + 5.5);
  doc.text('Total', 168, y + 5.5);

  y += 12;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(51, 65, 85);

  qt.items.forEach(item => {
    const descLines = doc.splitTextToSize(item.description, 85);
    doc.text(descLines, 24, y);
    doc.text(String(item.quantity), 116, y);
    doc.text(`${qt.currency} ${item.unitPrice.toLocaleString()}`, 135, y);
    doc.text(`${qt.currency} ${item.amount.toLocaleString()}`, 168, y);
    y += Math.max(descLines.length * 5, 8);
  });

  // Totals Box
  y += 5;
  doc.line(20, y, 190, y);
  y += 7;

  doc.setFont('helvetica', 'normal');
  doc.text('Subtotal:', 130, y);
  doc.text(`${qt.currency} ${qt.subtotal.toLocaleString()}`, 168, y);
  y += 6;

  if (qt.taxAmount > 0) {
    doc.text(`Tax / VAT (${qt.taxRate}%):`, 130, y);
    doc.text(`${qt.currency} ${qt.taxAmount.toLocaleString()}`, 168, y);
    y += 6;
  }

  if (qt.discountTotal > 0) {
    doc.text('Discount:', 130, y);
    doc.text(`- ${qt.currency} ${qt.discountTotal.toLocaleString()}`, 168, y);
    y += 6;
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(30, 64, 175);
  doc.text('Grand Total:', 130, y);
  doc.text(`${qt.currency} ${qt.total.toLocaleString()}`, 168, y);

  // Payment Terms & Notes
  y += 15;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(15, 23, 42);
  doc.text('Payment Terms & Conditions', 20, y);

  y += 6;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(71, 85, 105);
  const termsLines = doc.splitTextToSize(qt.paymentTerms || '30% Down Payment, 40% Mid-Development, 30% Upon Final Acceptance.', 170);
  doc.text(termsLines, 20, y);

  if (qt.notes) {
    y += termsLines.length * 5 + 4;
    doc.setFont('helvetica', 'bold');
    doc.text('Notes / Deliverables:', 20, y);
    y += 5;
    doc.setFont('helvetica', 'normal');
    const notesLines = doc.splitTextToSize(qt.notes, 170);
    doc.text(notesLines, 20, y);
  }

  // Footer
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text('This quotation is generated by NUNC Business Solutions management platform.', 20, 280);

  doc.save(`${qt.quotationNumber}.pdf`);
}

